
import streamlit as st
import pandas as pd
import joblib

# Load trained model
model = joblib.load('student_score_model.pkl')

# Page settings
st.set_page_config(
    page_title="Student Score Predictor",
    page_icon="🎓",
    layout="centered"
)

# App heading
st.title("🎓 Student Exam Score Predictor")

st.write(
    "Enter your academic and lifestyle information "
    "to predict your expected exam score."
)

st.divider()

# Student information
st.header("Student Information")

age = st.slider("Age", 17, 24, 20)

gender = st.selectbox(
    "Gender",
    ["male", "female", "other"]
)

course = st.selectbox(
    "Course",
    ["b.tech", "bca", "b.sc", "bba",
     "ba", "b.com", "diploma"]
)

st.divider()

# Academic information
st.header("Academic Details")

study_hours = st.slider(
    "Daily Study Hours",
    0.08, 7.91, 4.0
)

attendance = st.slider(
    "Class Attendance (%)",
    40.6, 99.4, 70.0
)

internet = st.selectbox(
    "Internet Access",
    ["yes", "no"]
)

st.divider()

# Lifestyle information
st.header("Lifestyle Details")

sleep_hours = st.slider(
    "Daily Sleep Hours",
    4.1, 9.9, 7.0
)

sleep_quality = st.selectbox(
    "Sleep Quality",
    ["poor", "average", "good"]
)

study_method = st.selectbox(
    "Study Method",
    ["coaching", "online videos", "mixed",
     "self-study", "group study"]
)

facility_rating = st.selectbox(
    "Study Facility Rating",
    ["low", "medium", "high"]
)

exam_difficulty = st.selectbox(
    "Exam Difficulty",
    ["hard", "moderate", "easy"]
)

st.divider()

# Prediction button
if st.button("Predict Exam Score", use_container_width=True):

    # Prepare input data
    input_data = pd.DataFrame([{
        'age': age,
        'gender': gender,
        'course': course,
        'study_hours': study_hours,
        'class_attendance': attendance,
        'internet_access': internet,
        'sleep_hours': sleep_hours,
        'sleep_quality': sleep_quality,
        'study_method': study_method,
        'facility_rating': facility_rating,
        'exam_difficulty': exam_difficulty
    }])

    # Predict score
    prediction = model.predict(input_data)[0]

    # Keep displayed score within 0–100
    prediction = max(0, min(100, prediction))

    st.success("Prediction completed!")

    st.metric(
        label="Predicted Exam Score",
        value=f"{prediction:.2f} / 100"
    )

    st.info(
        "This is an estimated score generated by a "
        "machine learning model. Actual exam results "
        "may differ."
    )

st.divider()

st.caption(
    "Student Exam Score Predictor | Machine Learning Project"
)
